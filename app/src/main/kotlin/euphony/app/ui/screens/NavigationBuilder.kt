import euphony.app.ui.screens.settings.PalettePickerScreen
import euphony.app.ui.screens.settings.PlayerSettings
import euphony.app.ui.screens.settings.PrivacySettings
import euphony.app.ui.screens.settings.SettingsScreen
import euphony.app.ui.screens.settings.StorageSettings
